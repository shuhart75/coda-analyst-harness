"""Launch only the pinned standalone orchestrator; never install during a run."""
import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import subprocess
import sys
import uuid

LOCK_PATH = Path(__file__).with_name('runtime-lock.json')
GIT_TIMEOUT = 30


class AdapterError(RuntimeError):
    pass


def git_env():
    env = dict(os.environ)
    for key in ('GIT_DIR', 'GIT_WORK_TREE', 'GIT_COMMON_DIR', 'GIT_INDEX_FILE',
                'GIT_OBJECT_DIRECTORY', 'GIT_ALTERNATE_OBJECT_DIRECTORIES',
                'GIT_CONFIG', 'GIT_CONFIG_COUNT', 'GIT_CONFIG_PARAMETERS'):
        env.pop(key, None)
    # Read-only validation must not rewrite the user's index.
    env['GIT_OPTIONAL_LOCKS'] = '0'
    env['GIT_TERMINAL_PROMPT'] = '0'
    return env


def git(root, *args, timeout=GIT_TIMEOUT):
    command = ['git', '-C', str(root), *args]
    try:
        result = subprocess.run(command, capture_output=True, text=True, encoding='utf-8',
                                errors='replace', timeout=timeout, env=git_env())
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise AdapterError('Не удалось проверить Git-копию оркестратора: ' + str(exc)) from exc
    if result.returncode:
        raise AdapterError('Git не подтвердил версию оркестратора: ' + result.stderr.strip()[:800])
    return result.stdout.strip()


def load_lock(path=None):
    path = Path(path or LOCK_PATH)
    try:
        if path.is_symlink() or path.stat().st_size > 16384:
            raise ValueError('unsafe or oversized lock')
        value = json.loads(path.read_text(encoding='utf-8'))
        if (not isinstance(value, dict) or value.get('schema') != 1
                or not isinstance(value.get('repository'), str)
                or not value['repository'].strip()
                or not re.fullmatch('[0-9a-f]{40}', value.get('commit', ''))
                or value['commit'] == '0' * 40):
            raise ValueError('invalid pin')
        return value
    except (OSError, ValueError, TypeError) as exc:
        raise AdapterError('Не задана корректная закреплённая версия SDD Orchestrator: ' + str(path)) from exc


def cache_root():
    override = os.environ.get('SDD_ORCHESTRATOR_CACHE')
    if override:
        return Path(override).expanduser().resolve()
    if sys.platform == 'darwin':
        base = Path.home() / 'Library' / 'Application Support'
    elif os.name == 'nt':
        base = Path(os.environ.get('LOCALAPPDATA', str(Path.home() / 'AppData' / 'Local')))
    else:
        base = Path(os.environ.get('XDG_DATA_HOME', str(Path.home() / '.local' / 'share')))
    return base / 'sdd-orchestrator'


def validate_runtime(root, lock):
    root = Path(root).expanduser()
    if root.is_symlink() or not root.is_dir():
        raise AdapterError('Копия оркестратора отсутствует или является ссылкой: ' + str(root))
    root = root.resolve()
    top = Path(git(root, 'rev-parse', '--show-toplevel')).resolve()
    if top != root:
        raise AdapterError('Каталог не является корнем отдельного репозитория оркестратора')
    if git(root, 'rev-parse', 'HEAD') != lock['commit']:
        raise AdapterError('Версия оркестратора отличается от закреплённой: ' + lock['commit'])
    # Ignore no tracked files, including changes staged in the index.
    if git(root, 'status', '--porcelain=v1', '--untracked-files=no'):
        raise AdapterError('В закреплённой копии оркестратора изменены отслеживаемые файлы; сохраните их отдельно')
    # Git status trusts assume-unchanged/skip-worktree index flags. Verify bytes
    # against HEAD itself so those local flags cannot substitute executable code.
    for row in git(root, 'ls-tree', '-r', '-z', '--full-tree', 'HEAD').split('\0'):
        if not row:
            continue
        header, name = row.split('\t', 1)
        mode, kind, expected = header.split()
        target = root / name
        if kind != 'blob' or mode not in ('100644', '100755') or target.is_symlink() or not target.is_file():
            raise AdapterError('Неподдерживаемый или отсутствующий файл закреплённой версии: ' + name)
        data = target.read_bytes()
        actual = hashlib.sha1(b'blob ' + str(len(data)).encode('ascii') + b'\0' + data).hexdigest()
        if actual != expected:
            raise AdapterError('Содержимое файла отличается от закреплённого коммита: ' + name)
    # Ignored executable modules can shadow imports just like visible files.
    # Ordinary diagnostic files and generated bytecode caches need not block a run.
    paths = []
    for ignored in (False, True):
        args = ['ls-files', '--others', '--exclude-standard', '-z']
        if ignored:
            args.append('--ignored')
        paths.extend(git(root, *args).split('\0'))
    for name in paths:
        path = Path(name)
        if name and path.suffix.lower() in ('.py', '.pyw', '.pyc', '.pyd', '.so', '.dll'):
            if path.suffix == '.pyc' and '__pycache__' in path.parts:
                continue  # Launch uses a fresh external cache, so these are never loaded.
            raise AdapterError('Незарегистрированный исполняемый модуль в копии оркестратора: ' + name)
    return root


def resolve_runtime(lock_path=None):
    lock = load_lock(lock_path)
    override = os.environ.get('SDD_ORCHESTRATOR_HOME')
    root = Path(override).expanduser() if override else cache_root() / 'versions' / lock['commit']
    try:
        return validate_runtime(root, lock)
    except AdapterError as exc:
        installer = Path(__file__).with_name('install.py')
        command = ('PowerShell: & ' + ' '.join("'" + arg.replace("'", "''") + "'"
                    for arg in (sys.executable, str(installer)))) if os.name == 'nt' else shlex.join([sys.executable, str(installer)])
        raise AdapterError(str(exc) + '\nУстановите закреплённую версию явно: '
                           + command + '. '
                           'Текущий запуск и его данные не изменены.') from exc


def launch(command, env):
    if sys.platform != 'win32':
        os.execve(sys.executable, command, env)
        return 0
    # Windows has no POSIX process replacement. Share the console so Ctrl-C
    # reaches the controller, then wait for its own guarded cleanup.
    child = subprocess.Popen(command, env=env)
    while True:
        try:
            return child.wait()
        except KeyboardInterrupt:
            continue


def main(entry, argv=None, *, lock_path=None):
    try:
        if not isinstance(entry, str) or not re.fullmatch(r'[a-z][a-z0-9_]*\.py', entry):
            raise AdapterError('Недопустимая точка входа оркестратора')
        root = resolve_runtime(lock_path)
        target = root / entry
        if target.is_symlink() or not target.is_file() or git(root, 'ls-files', '--', entry) != entry:
            raise AdapterError('Закреплённая версия не содержит точку входа: ' + entry)
        # Ignore external PYTHONPATH/user site and use a fresh bytecode directory.
        # Existing ignored .pyc files in an installed checkout cannot shadow source.
        cache = str(cache_root() / '.bytecode-disabled' / uuid.uuid4().hex)
        command = [sys.executable, '-E', '-s', '-B', '-X', 'pycache_prefix=' + cache,
                   str(target), *(sys.argv[1:] if argv is None else argv)]
        env = dict(os.environ)
        env['SDD_HARNESS_ROOT'] = str(Path(__file__).resolve().parents[2])
        env['PYTHONPYCACHEPREFIX'] = cache
        env['PYTHONDONTWRITEBYTECODE'] = '1'
        return launch(command, env)
    except (AdapterError, OSError) as exc:
        print(str(exc), file=sys.stderr)
        return 2
    except KeyboardInterrupt:
        return 130
